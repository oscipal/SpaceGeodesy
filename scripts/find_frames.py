"""Stage 1: find LiCSAR frames covering the AOI and summarise their interferogram networks.

For every frame on the candidate tracks (config: licsar.candidate_tracks, plus
licsar.neighbour_tracks if set):
  1. footprint polygon (metadata/<frame>-poly.txt) -> AOI area fraction covered
  2. AOI window of metadata hgt + landmask, read remotely via GDAL /vsicurl/
     (no full download) -> fraction of AOI land pixels with valid data
  3. interferogram listing -> epochs, ifgs, gaps, sampling per year, connectivity
Selects one ascending and one descending frame and writes them to config.yaml
and docs/frames.md.
"""
from __future__ import annotations

import datetime as dt
import json
import re
import sys
from collections import Counter

import numpy as np
from osgeo import gdal

from common import (CONFIG_PATH, ROOT, aoi_box, frame_polygon, frame_url,
                    list_frames, list_ifgs, load_config, path)

gdal.UseExceptions()

MIN_LAND_COVERAGE = 0.99   # fraction of AOI land pixels that must have valid data
GAP_DAYS = 24              # report gaps between consecutive epochs longer than this


def read_aoi(url: str, cfg: dict) -> np.ndarray | None:
    a = cfg["aoi"]
    try:
        ds = gdal.Translate("", f"/vsicurl/{url}", format="MEM",
                            projWin=[a["lon_min"], a["lat_max"], a["lon_max"], a["lat_min"]])
    except RuntimeError as e:
        print(f"    could not read {url}: {e}")
        return None
    arr = ds.GetRasterBand(1).ReadAsArray().astype("float64")
    nd = ds.GetRasterBand(1).GetNoDataValue()
    if nd is not None:
        arr[arr == nd] = np.nan
    return arr


def raster_coverage(cfg: dict, frame: str) -> dict:
    meta = f"{frame_url(cfg, frame)}/metadata/{frame}"
    hgt = read_aoi(f"{meta}.geo.hgt.tif", cfg)
    land = read_aoi(f"{meta}.geo.landmask.tif", cfg)
    if hgt is None:
        return {"land_coverage": None, "valid_fraction": None, "shape": None}
    valid = np.isfinite(hgt) & (hgt != 0)
    out = {"shape": list(hgt.shape), "valid_fraction": float(valid.mean())}
    if land is not None and land.shape == hgt.shape:
        is_land = land > 0
        out["land_pixels"] = int(is_land.sum())
        # landmask itself is only defined inside the frame; hgt validity is the test
        out["land_coverage"] = float(valid[is_land].mean()) if is_land.any() else None
    else:
        out["land_coverage"] = None
    return out


def network_summary(pairs, start: dt.date, end: dt.date) -> dict:
    pairs = [(a, b) for a, b in pairs if a >= start and b <= end]
    if not pairs:
        return {"n_ifgs": 0, "n_epochs": 0}
    epochs = sorted({d for p in pairs for d in p})
    gaps = [(e0.isoformat(), e1.isoformat(), (e1 - e0).days)
            for e0, e1 in zip(epochs[:-1], epochs[1:]) if (e1 - e0).days > GAP_DAYS]

    # median epoch spacing per calendar year (effective revisit)
    by_year: dict[int, list[int]] = {}
    for e0, e1 in zip(epochs[:-1], epochs[1:]):
        by_year.setdefault(e1.year, []).append((e1 - e0).days)
    sampling = {y: {"median_days": float(np.median(v)), "n_epochs": len(v)}
                for y, v in sorted(by_year.items())}

    # connectivity of the ifg network (union-find over epochs)
    parent = {e: e for e in epochs}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for a, b in pairs:
        parent[find(a)] = find(b)
    comps = Counter(find(e) for e in epochs)
    components = []
    for root in comps:
        members = [e for e in epochs if find(e) == root]
        components.append({"first": members[0].isoformat(), "last": members[-1].isoformat(),
                           "n_epochs": len(members)})
    components.sort(key=lambda c: c["first"])

    btemp = Counter((b - a).days for a, b in pairs)
    return {
        "n_ifgs": len(pairs),
        "n_epochs": len(epochs),
        "first_epoch": epochs[0].isoformat(),
        "last_epoch": epochs[-1].isoformat(),
        "days_since_last_epoch": (dt.date.today() - epochs[-1]).days,
        "gaps": gaps,
        "sampling_per_year": sampling,
        "components": components,
        "btemp_top": btemp.most_common(8),
    }


def update_config_frames(asc: str | None, desc: str | None) -> None:
    text = CONFIG_PATH.read_text(encoding="utf-8")
    for key, val in (("ascending", asc), ("descending", desc)):
        text = re.sub(rf"^(\s+{key}:)[^\n#]*", rf"\g<1> {val or 'null'}", text,
                      count=1, flags=re.M)
    CONFIG_PATH.write_text(text, encoding="utf-8")


def write_frames_md(cfg, results, chosen, base_url) -> None:
    a = cfg["aoi"]
    t = cfg["time"]
    L = ["# LiCSAR frame selection", "",
         f"Generated by `scripts/find_frames.py` on {dt.date.today().isoformat()}.", "",
         f"- Server: {base_url}",
         f"- AOI: lon {a['lon_min']} to {a['lon_max']}, lat {a['lat_min']} to {a['lat_max']}",
         f"- Time window: {t['start']} to {t['end']}",
         f"- Tracks searched: {sorted({r['track'] for r in results})}", "",
         "## Selected frames", ""]
    for d, f in chosen.items():
        L.append(f"- **{d}**: `{f}`" if f else f"- **{d}**: none passed the coverage test")
    L += ["", "## Candidates intersecting the AOI", "",
          "| Frame | AOI area in footprint | AOI land pixels with data | ifgs | epochs | first | last | days since last |",
          "|---|---|---|---|---|---|---|---|"]
    for r in results:
        if not r.get("intersects"):
            continue
        n = r.get("network", {})
        lc = r["raster"].get("land_coverage")
        L.append(f"| `{r['frame']}` | {r['area_fraction']:.3f} | "
                 f"{'n/a' if lc is None else f'{lc:.3f}'} | {n.get('n_ifgs', 0)} | "
                 f"{n.get('n_epochs', 0)} | {n.get('first_epoch', '')} | {n.get('last_epoch', '')} | "
                 f"{n.get('days_since_last_epoch', '')} |")
    others = [r["frame"] for r in results if not r.get("intersects")]
    L += ["", f"Frames on these tracks that do not intersect the AOI: {', '.join(others) or 'none'}.", ""]

    for d, f in chosen.items():
        if not f:
            continue
        r = next(x for x in results if x["frame"] == f)
        n = r["network"]
        L += [f"## {f} ({d})", "",
              f"- Evidence: {frame_url(cfg, f)}/metadata/{f}-poly.txt, "
              f"`{f}.geo.hgt.tif`, `{f}.geo.landmask.tif`, `interferograms/` listing",
              f"- {n['n_ifgs']} interferograms, {n['n_epochs']} epochs, "
              f"{n['first_epoch']} to {n['last_epoch']}",
              f"- Network components: {len(n['components'])}"
              + ("" if len(n["components"]) == 1 else
                 " (DISCONNECTED: " + "; ".join(f"{c['first']}..{c['last']} ({c['n_epochs']} ep)"
                                               for c in n["components"]) + ")"),
              f"- Most common temporal baselines (days, count): {n['btemp_top']}", "",
              "Effective sampling (median spacing between consecutive epochs):", "",
              "| Year | median days | epochs |", "|---|---|---|"]
        for y, s in n["sampling_per_year"].items():
            L.append(f"| {y} | {s['median_days']:.0f} | {s['n_epochs']} |")
        L += ["", f"Gaps longer than {GAP_DAYS} days:", ""]
        L += [f"- {g0} to {g1}: {days} days" for g0, g1, days in n["gaps"]] or ["- none"]
        L.append("")
    (path(cfg, "docs") / "frames.md").write_text("\n".join(L), encoding="utf-8")


def main() -> int:
    cfg = load_config()
    lc = cfg["licsar"]
    tracks = list(lc["candidate_tracks"]) + list(lc.get("neighbour_tracks") or [])
    aoi = aoi_box(cfg)
    results = []
    for track in tracks:
        frames = list_frames(cfg, track)
        print(f"track {track}: {len(frames)} frames")
        for f in frames:
            poly = frame_polygon(cfg, f)
            r = {"frame": f, "track": track, "direction": "ascending" if f[3] == "A" else "descending"}
            r["intersects"] = bool(poly is not None and poly.intersects(aoi))
            r["area_fraction"] = float(poly.intersection(aoi).area / aoi.area) if r["intersects"] else 0.0
            results.append(r)
            if not r["intersects"]:
                continue
            print(f"  {f}: AOI area in footprint {r['area_fraction']:.3f}, reading AOI window ...")
            r["raster"] = raster_coverage(cfg, f)
            r["network"] = network_summary(list_ifgs(cfg, f), cfg["time"]["start"], cfg["time"]["end"])
            print(f"    land coverage {r['raster'].get('land_coverage')}, "
                  f"{r['network'].get('n_ifgs')} ifgs / {r['network'].get('n_epochs')} epochs in window")

    chosen = {}
    for d in ("ascending", "descending"):
        ok = [r for r in results if r["direction"] == d and r["intersects"]
              and (r["raster"].get("land_coverage") or 0) >= MIN_LAND_COVERAGE
              and r["network"].get("n_epochs", 0) > 0]
        ok.sort(key=lambda r: r["network"]["n_epochs"], reverse=True)
        chosen[d] = ok[0]["frame"] if ok else None
        if not ok:
            print(f"WARNING: no {d} frame covers >= {MIN_LAND_COVERAGE:.0%} of AOI land. "
                  f"Add tracks to licsar.neighbour_tracks in config.yaml and re-run.")

    out = path(cfg, "results") / "frames"
    out.mkdir(exist_ok=True)
    (out / "summary.json").write_text(json.dumps(results, indent=1, default=str), encoding="utf-8")
    update_config_frames(chosen["ascending"], chosen["descending"])
    write_frames_md(cfg, results, chosen, lc["base_url"])
    print(f"selected: {chosen}  -> config.yaml, docs/frames.md, {out.relative_to(ROOT)}/summary.json")
    return 0 if all(chosen.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
